//! GitHub's timestamps in ms since the Unix epoch.

use super::*;

#[test]
fn utc_timestamps_parse_to_milliseconds() {
    for (text, wanted) in [
        ("1970-01-01T00:00:00Z", 0),
        ("1970-01-01T00:00:01Z", 1_000),
        ("2000-02-29T12:00:00Z", 951_825_600_000),
        ("2000-03-01T00:00:00Z", 951_868_800_000),
        // The fixture repos' first commit (`dv_test_support::EPOCH`).
        ("2026-01-01T00:00:00Z", dv_test_support::EPOCH as u64 * 1000),
        ("2026-10-19T08:30:15Z", 1_792_398_615_000),
        ("2026-10-19T08:30:15.5Z", 1_792_398_615_500),
        ("2026-10-19T08:30:15.123456Z", 1_792_398_615_123),
        ("2100-03-01T00:00:00Z", 4_107_542_400_000),
        ("2024-02-29T00:00:00Z", 1_709_164_800_000),
    ] {
        assert_eq!(parse_timestamp(text), Some(wanted), "{text}");
    }
}

#[test]
fn anything_else_is_no_timestamp() {
    for text in [
        "",
        "2026-10-19",
        "2026-10-19T08:30:15",
        "2026-10-19T08:30:15+02:00",
        "2026-10-19 08:30:15Z",
        "2026-13-19T08:30:15Z",
        "2026-00-19T08:30:15Z",
        "2026-10-32T08:30:15Z",
        // A day the month doesn't have.
        "2026-02-29T08:30:15Z",
        "2026-02-30T08:30:15Z",
        "2100-02-29T08:30:15Z",
        "2026-04-31T08:30:15Z",
        "2026-11-31T08:30:15Z",
        "2026-10-19T24:30:15Z",
        "2026-10-19T08:60:15Z",
        "2026-10-19T08:30:15.Zz",
        "2026-10-19T08:30:15.x1Z",
        "26-10-19T08:30:15Z",
        "2026-1-19T08:30:15Z",
        "+026-10-19T08:30:15Z",
        "1969-12-31T23:59:59Z",
        "2026-10-19T08:30Z",
        "2026-10-19-01T08:30:15Z",
    ] {
        assert_eq!(parse_timestamp(text), None, "{text:?}");
    }
}
